// Regenerates lib/src/runtime/cupertino_icons_metadata.dart from a Flutter
// checkout (or a directory holding packages/flutter/lib/src/cupertino/
// icons.dart):
//   dart run tool/generate_cupertino_metadata.dart <flutter-dir>
import 'dart:io';

import 'package:path/path.dart' as p;

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'Usage: dart run tool/generate_cupertino_metadata.dart <flutter-dir>',
    );
    exitCode = 64;
    return;
  }
  final source = File(
    p.join(args.single, 'packages/flutter/lib/src/cupertino/icons.dart'),
  ).readAsStringSync();
  final constant = RegExp(
    r'static const IconData (\w+) = (?:IconData\(([^)]*)\)|(\w+));',
  );
  final icons = <String, (String, bool)>{};
  final lines = <String>[];
  for (final match in constant.allMatches(source)) {
    final name = match.group(1)!;
    final body = match.group(2);
    final (String, bool)? icon;
    if (body != null) {
      icon = (
        RegExp(r'0x[0-9a-fA-F]+').firstMatch(body)!.group(0)!,
        body.contains('matchTextDirection: true'),
      );
      icons[name] = icon;
    } else {
      icon = icons[match.group(3)];
    }
    if (icon == null) continue;
    lines.add(
      '  static const $name = IconData(${icon.$1}, fontFamily: iconFont, '
      'fontPackage: iconFontPackage${icon.$2 ? ', matchTextDirection: true' : ''});',
    );
  }
  File('lib/src/runtime/cupertino_icons_metadata.dart').writeAsStringSync('''
// GENERATED by tool/generate_cupertino_metadata.dart.
// Cupertino icon code points from Flutter; see THIRD_PARTY_NOTICES.md. The
// glyphs come from the cupertino_icons package font; this file contains
// metadata only.
// ignore_for_file: constant_identifier_names
import 'visual_metadata.dart';

abstract final class CupertinoIcons {
  static const String iconFont = 'CupertinoIcons';
  static const String iconFontPackage = 'cupertino_icons';
${lines.join('\n')}
}
''');
  Process.runSync(Platform.resolvedExecutable, [
    'format',
    'lib/src/runtime/cupertino_icons_metadata.dart',
  ]);
}
