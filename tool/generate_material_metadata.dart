// Regenerates runtime Material icon and color metadata from Flutter sources.
//
//   dart run tool/generate_material_metadata.dart <flutter-checkout-or-dir>
//
// The directory must contain Flutter's `icons.dart` and `colors.dart`, either
// at their repository paths or directly. Output is value metadata only; the
// icon font itself is supplied at build time.
import 'dart:io';

import 'package:path/path.dart' as p;

File _find(String root, String name) {
  for (final candidate in [
    p.join(root, 'packages/flutter/lib/src/material', name),
    p.join(root, name),
  ]) {
    if (File(candidate).existsSync()) return File(candidate);
  }
  throw ArgumentError('Missing $name under $root.');
}

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'Usage: dart run tool/generate_material_metadata.dart <flutter-dir>',
    );
    exitCode = 64;
    return;
  }
  final icons = _find(args.single, 'icons.dart').readAsStringSync();
  final colors = _find(args.single, 'colors.dart').readAsStringSync();
  File(
    'lib/src/runtime/material_icons_metadata.dart',
  ).writeAsStringSync(_icons(icons));
  File(
    'lib/src/runtime/material_colors.dart',
  ).writeAsStringSync(_colors(colors));
  final format = Process.runSync(Platform.resolvedExecutable, [
    'format',
    'lib/src/runtime/material_icons_metadata.dart',
    'lib/src/runtime/material_colors.dart',
  ]);
  if (format.exitCode != 0) throw StateError('${format.stderr}');
}

String _icons(String source) {
  final constant = RegExp(
    r'static const IconData (\w+) =\s*IconData\(\s*(0x[0-9a-fA-F]+),\s*fontFamily: '
    r"'MaterialIcons',?\s*(matchTextDirection: true,?)?\s*\);",
  );
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_material_metadata.dart.')
    ..writeln('// Material icon code points from Flutter; see')
    ..writeln('// THIRD_PARTY_NOTICES.md. The glyphs come from the build\'s')
    ..writeln('// MaterialIcons font; this file contains metadata only.')
    ..writeln('// ignore_for_file: constant_identifier_names')
    ..writeln("import 'visual_metadata.dart';")
    ..writeln()
    ..writeln('abstract final class Icons {')
    ..writeln('  static const adaptive = PlatformAdaptiveIcons._();');
  var count = 0;
  for (final match in constant.allMatches(source)) {
    final mirrored = match.group(3) != null;
    out.writeln(
      "  static const ${match.group(1)} = IconData(${match.group(2)}, fontFamily: 'MaterialIcons'${mirrored ? ', matchTextDirection: true' : ''});",
    );
    count++;
  }
  if (count < 1000) throw StateError('Unexpected icon source format.');
  out.writeln('}');
  // Browsers other than iOS/macOS Safari use the Material variants, which is
  // what Flutter web selects for non-Apple platforms.
  final adaptive = RegExp(
    r'IconData get (\w+) =>\s*!_isCupertino\(\) \? Icons\.(\w+) : Icons\.\w+;',
  );
  out
    ..writeln()
    ..writeln('final class PlatformAdaptiveIcons {')
    ..writeln('  const PlatformAdaptiveIcons._();');
  for (final match in adaptive.allMatches(source)) {
    out.writeln('  IconData get ${match.group(1)} => Icons.${match.group(2)};');
  }
  out.writeln('}');
  return out.toString();
}

String _colors(String source) {
  final start = source.indexOf('abstract final class Colors {');
  if (start < 0) throw StateError('Unexpected color source format.');
  var depth = 0, end = start;
  for (var i = source.indexOf('{', start); i < source.length; i++) {
    if (source[i] == '{') depth++;
    if (source[i] == '}' && --depth == 0) {
      end = i + 1;
      break;
    }
  }
  final body = source
      .substring(start, end)
      .split('\n')
      .where((line) => !line.trimLeft().startsWith('//'))
      .join('\n');
  return '''
// GENERATED by tool/generate_material_metadata.dart.
// Material 2 color swatches from Flutter; see THIRD_PARTY_NOTICES.md.
import 'visual_metadata.dart';

class ColorSwatch<T> extends Color {
  const ColorSwatch(super.primary, this._swatch);
  final Map<T, Color> _swatch;
  Color? operator [](T key) => _swatch[key];
  Iterable<T> get keys => _swatch.keys;
}

class MaterialColor extends ColorSwatch<int> {
  const MaterialColor(super.primary, super.swatch);
  Color get shade50 => this[50]!;
  Color get shade100 => this[100]!;
  Color get shade200 => this[200]!;
  Color get shade300 => this[300]!;
  Color get shade400 => this[400]!;
  Color get shade500 => this[500]!;
  Color get shade600 => this[600]!;
  Color get shade700 => this[700]!;
  Color get shade800 => this[800]!;
  Color get shade900 => this[900]!;
}

class MaterialAccentColor extends ColorSwatch<int> {
  const MaterialAccentColor(super.primary, super.swatch);
  Color get shade50 => this[50]!;
  Color get shade100 => this[100]!;
  Color get shade200 => this[200]!;
  Color get shade400 => this[400]!;
  Color get shade700 => this[700]!;
}

$body
''';
}
